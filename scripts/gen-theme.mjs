// Regenerates src/app/theme-palette.css from Tailwind's default palette.
// Usage: node scripts/gen-theme.mjs   (rerun after upgrading tailwindcss)
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const colors = Object.fromEntries([...src.matchAll(/--color-([a-z]+-\d+):\s*([^;]+);/g)].map((m) => [m[1], m[2]]));

const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const NEUTRALS = ['neutral', 'gray', 'zinc', 'slate', 'stone'];
const ACCENTS = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];
// Warm paper-to-ink ramp. 900/950 are surfaces (lighter than the page), 800/700 borders and hovers.
const PAPER = {
  50: '#161d19', 100: '#212a25', 200: '#2e3832', 300: '#424c46', 400: '#5b665f', 500: '#78827b',
  600: '#9fa69f', 700: '#d3cfc2', 800: '#e7e3d8', 900: '#fdfcf8', 950: '#f7f5ef',
};
const mirror = Object.fromEntries(SHADES.map((s, i) => [s, SHADES[SHADES.length - 1 - i]]));
const row = (hue, value) => '  ' + SHADES.map((s) => `--color-${hue}-${s}: ${value(s)};`).join(' ');

const lines = [
  '/* Generated by scripts/gen-theme.mjs from tailwindcss/theme.css — do not edit by hand. */',
  '/*',
  ' * Light theme ("paper atlas"). The UI is written dark-first with Tailwind palette classes;',
  ' * light mode remaps the palette variables instead of touching every className:',
  ' *   black/white      -> paper / ink',
  ' *   neutral scales   -> a warm paper-to-ink ramp (900/950 become raised surfaces)',
  ' *   accent hues      -> shade-mirrored (400 <-> 600 ...) so tints and text keep their contrast',
  ' * Any subtree can opt back into the dark palette with data-theme="dark".',
  ' */',
  ':root[data-theme="light"], [data-theme="light"] {',
  '  color-scheme: light;',
  '  --background: #f1ede4;',
  '  --foreground: #161d19;',
  '  --color-black: #f1ede4;',
  '  --color-white: #161d19;',
  ...NEUTRALS.map((hue) => row(hue, (s) => PAPER[s])),
  ...ACCENTS.map((hue) => row(hue, (s) => colors[`${hue}-${mirror[s]}`])),
  '}',
  '',
  '[data-theme="dark"] {',
  '  color-scheme: dark;',
  '  --background: #000000;',
  '  --foreground: #ededed;',
  '  --color-black: #000;',
  '  --color-white: #fff;',
  ...[...NEUTRALS, ...ACCENTS].map((hue) => row(hue, (s) => colors[`${hue}-${s}`])),
  '}',
];
writeFileSync(new URL('../src/app/theme-palette.css', import.meta.url), lines.join('\n') + '\n');
console.log(`wrote src/app/theme-palette.css (${lines.length} lines)`);
